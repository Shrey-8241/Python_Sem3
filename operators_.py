print("IDENTITY OPERATORS\n")
a=10
b=20
c=a
print (a is not b)
print (a is c)

print("\nMEMBERSHIP OPERATORS\n")
print('a' in 'apple')
print('b' in 'apple')

print("\nASSIGNMENT OPERATORS\n")
x=10
print("X=",x)
x+=3
print('x+=3',x)
x-=3
print('x-=3',x)
x*=3
print('x*=3',x)
x/=3
print('x/=3',x)
x//=3
print('x//=3',x)
x%=3
print('x%=3',x)
x**=3
print('x**=3',x)

print("\nARITHMETIC OPERATORS\n")
print("a+b ",a+b)
print("a-b ",a-b)
print("a/b ",a/b)
print("a*b ",a*b)
print("a%b ",a%b)


print("\nBITWISE OPERATORS\n")
y = 12
q = 10

print(y & q)
print(y | q)
print(y ^ q)   
print(~y)   
print(y << 2)
print(y >> 2)

print("\nLOGICAL OPERATORS\n")
print(y and q)
print(y or q)
print(not q) 
